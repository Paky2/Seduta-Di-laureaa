    private JButton rifiutaButton;
    private JButton chiudiButton;

    private Controller controller;

    private List<Tesi> tesi;

    public GestioneTesiGUI() {

        controller = new Controller();

        caricaTesi();

        accettaButton.addActionListener(
                e -> aggiornaTesi(true)
        );

        rifiutaButton.addActionListener(
                e -> aggiornaTesi(false)
        );

        chiudiButton.addActionListener(
                e -> chiudiFinestra()
        );
    }

    private void caricaTesi() {

        tesi =
                controller.ListaTesi();

        DefaultListModel<String> model =
                new DefaultListModel<>();

        if (tesi.isEmpty()) {

            model.addElement(
                    "Nessuna tesi presente."
            );

        } else {

            for (Tesi t : tesi) {

                String testo =
                        "ID: "
                                + t.getId()
                                + " | Studente: "
                                + t.getStudente().getMatricola()
                                + " | File: "
                                + t.getFile()
                                + " | Versione: "
                                + t.getVersione()
                                + " | Stato: "
                                + t.getStato();

                model.addElement(testo);
            }
        }

        tesiList.setModel(model);
    }

    private void aggiornaTesi(boolean accetta) {

        int indice =
                tesiList.getSelectedIndex();

        if (indice < 0
                || tesi.isEmpty()
                || indice >= tesi.size()) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Seleziona una tesi.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        Tesi tesiSelezionata =
                tesi.get(indice);

        if (accetta) {

            tesiSelezionata.setStato(
                    StatoTesi.ACCETTATA
            );

        } else {

            tesiSelezionata.setStato(
                    StatoTesi.RIFIUTATA
            );
        }

        controller.AccettaORifiutaTesi(
                tesiSelezionata
        );

        JOptionPane.showMessageDialog(
                mainPanel,
                accetta
                        ? "Tesi accettata."
                        : "Tesi rifiutata."
        );

        caricaTesi();
    }

    private void chiudiFinestra() {

        Window window =
                SwingUtilities.getWindowAncestor(
                        mainPanel
                );

        if (window != null) {
            window.dispose();
        }
    }

