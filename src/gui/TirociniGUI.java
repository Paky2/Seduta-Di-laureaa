    private Controller controller;
    private List<Tirocinio> tirocini;

    public TirociniGUI() {

        controller = new Controller();

        caricaTirocini();

        chiudiButton.addActionListener(
                e -> chiudiFinestra()
        );
    }

    private void caricaTirocini() {

        tirocini =
                controller.ListaTirocini();

        DefaultListModel<String> model =
                new DefaultListModel<>();

        if (tirocini.isEmpty()) {

            model.addElement(
                    "Nessun tirocinio disponibile."
            );

        } else {

            for (Tirocinio tirocinio : tirocini) {

                String tipo;

                if (tirocinio instanceof TirocinioEsterno) {
                    tipo = "Esterno";
                } else {
                    tipo = "Interno";
                }

                String docente =
                        tirocinio.getDocenteResponsabile()
                                .toString();

                model.addElement(
                        "ID: " + tirocinio.getId()
                                + " | "
                                + tirocinio.getArgomento()
                                + " | Tipo: "
                                + tipo
                                + " | Docente: "
                                + docente
                );
            }
        }

        tirociniList.setModel(model);
    }

    private void chiudiFinestra() {

        Window window =
                SwingUtilities.getWindowAncestor(
                        mainPanel
                );

        if (window != null) {
            window.dispose();
        }
    }

