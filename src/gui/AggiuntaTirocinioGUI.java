    private Controller controller;
    private Docente docenteResponsabile;

    public AggiuntaTirocinioGUI(Docente docenteResponsabile) {

        this.docenteResponsabile = docenteResponsabile;

        controller = new Controller();

        tipoTirocinioComboBox.removeAllItems();
        tipoTirocinioComboBox.addItem("INTERNO");
        tipoTirocinioComboBox.addItem("ESTERNO");

        tipoTirocinioComboBox.addActionListener(
                e -> aggiornaReferente()
        );

        salvaButton.addActionListener(
                e -> salvaTirocinio()
        );

        indietroButton.addActionListener(
                e -> chiudiFinestra()
        );

        aggiornaReferente();
    }

    private void aggiornaReferente() {

        boolean esterno =
                "ESTERNO".equals(
                        tipoTirocinioComboBox.getSelectedItem()
                );

        referenteField.setEnabled(esterno);

        if (!esterno) {
            referenteField.setText("");
        }
    }

    private void salvaTirocinio() {

        String argomento =
                argomentoField.getText().trim();

        String tipo =
                (String) tipoTirocinioComboBox.getSelectedItem();

        String referente =
                referenteField.getText().trim();

        if (argomento.isEmpty()) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Inserisci l'argomento del tirocinio.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        if ("ESTERNO".equals(tipo)
                && referente.isEmpty()) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Inserisci il referente aziendale.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        Tirocinio tirocinio;

        if ("ESTERNO".equals(tipo)) {

            tirocinio =
                    new TirocinioEsterno(
                            0,
                            argomento,
                            docenteResponsabile,
                            StatoTirocinio.IN_CORSO,
                            referente
                    );

        } else {

            tirocinio =
                    new TirocinioInterno(
                            0,
                            argomento,
                            docenteResponsabile,
                            StatoTirocinio.IN_CORSO
                    );
        }

        controller.AggiuntaArgomentoTirocinio(
                tirocinio
        );

        JOptionPane.showMessageDialog(
                mainPanel,
                "Tirocinio salvato correttamente."
        );

        argomentoField.setText("");
        referenteField.setText("");

        tipoTirocinioComboBox.setSelectedItem(
                "INTERNO"
        );
    }

    private void chiudiFinestra() {

        Window window =
                SwingUtilities.getWindowAncestor(
                        mainPanel
                );

        if (window != null) {
            window.dispose();
        }
    }

