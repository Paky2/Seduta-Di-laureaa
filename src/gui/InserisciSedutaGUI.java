    private void salvaSeduta() {

        String dataTesto =
                dataField.getText().trim();

        String oraTesto =
                oraField.getText().trim();

        String luogo =
                luogoField.getText().trim();

        if (dataTesto.isEmpty()
                || oraTesto.isEmpty()
                || luogo.isEmpty()) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Compila tutti i campi.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        Date data;

        try {

            SimpleDateFormat formato =
                    new SimpleDateFormat(
                            "yyyy-MM-dd"
                    );

            formato.setLenient(false);

            data =
                    formato.parse(
                            dataTesto
                    );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "La data deve avere formato yyyy-MM-dd.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        LocalTime ora;

        try {

            ora =
                    LocalTime.parse(
                            oraTesto,
                            DateTimeFormatter.ofPattern(
                                    "HH:mm"
                            )
                    );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "L'ora deve avere formato HH:mm.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        SedutaLaurea seduta =
                new SedutaLaurea(
                        0,
                        data,
                        ora,
                        luogo,
                        true
                );

        controller.InserisciSedutaLaurea(
                seduta
        );

        JOptionPane.showMessageDialog(
                mainPanel,
                "Seduta inserita correttamente."
        );

        dataField.setText("");
        oraField.setText("");
        luogoField.setText("");
    }

    private void chiudiFinestra() {

        Window window =
                SwingUtilities.getWindowAncestor(
                        mainPanel
                );

        if (window != null) {
            window.dispose();
        }
    }

