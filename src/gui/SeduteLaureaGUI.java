    private Controller controller;

    private String loginStudente;

    private List<SedutaLaurea> seduteDisponibili =
            new ArrayList<>();

    public SeduteLaureaGUI(String loginStudente) {

        this.loginStudente = loginStudente;

        controller = new Controller();

        caricaSedute();

        prenotaButton.addActionListener(
                e -> prenotaSeduta()
        );

        chiudiButton.addActionListener(
                e -> chiudiFinestra()
        );
    }

    private void caricaSedute() {

        List<SedutaLaurea> sedute =
                controller.ListaSedute();

        seduteDisponibili.clear();

        DefaultListModel<String> model =
                new DefaultListModel<>();

        for (SedutaLaurea seduta : sedute) {

            // Mostra tutte le sedute libere, non soltanto
            // quella già associata alla tesi.
            if (seduta.isDisponibilita()) {

                seduteDisponibili.add(seduta);

                model.addElement(
                        "ID: " + seduta.getId()
                                + " | Data: " + seduta.getData()
                                + " | Ora: " + seduta.getOra()
                                + " | Luogo: " + seduta.getLuogo()
                );
            }
        }

        if (seduteDisponibili.isEmpty()) {
            model.addElement(
                    "Nessuna seduta disponibile."
            );
        }

        seduteList.setModel(model);
    }

    private void prenotaSeduta() {

        int indice =
                seduteList.getSelectedIndex();

        if (indice < 0 || indice >= seduteDisponibili.size()) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Seleziona una seduta prenotabile.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        Studente studente =
                controller.OttieniStudente(loginStudente);

        if (studente == null) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Studente non trovato.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        SedutaLaurea seduta =
                seduteDisponibili.get(indice);

        try {



            if (!controller.StudenteHaTesiAccettataPerSeduta(
                    studente.getMatricola(),
                    seduta.getId())) {

                JOptionPane.showMessageDialog(
                        mainPanel,
                        "Non puoi prenotare: la tesi associata "
                                + "a questa seduta non è stata accettata.",
                        "Prenotazione non consentita",
                        JOptionPane.WARNING_MESSAGE
                );

                caricaSedute();
                return;
            }

            controller.PrenotaSedutaLaurea(
                    seduta,
                    studente
            );

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Seduta prenotata correttamente.",
                    "Successo",
                    JOptionPane.INFORMATION_MESSAGE
            );

            caricaSedute();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Prenotazione non effettuata:\n"
                            + e.getMessage(),
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();

            caricaSedute();
        }
    }

    private void chiudiFinestra() {

        Window window =
                SwingUtilities.getWindowAncestor(
                        mainPanel
                );

        if (window != null) {
            window.dispose();
        }
    }

