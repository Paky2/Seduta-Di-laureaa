    public GestioneRichiesteGUI() {

        controller = new Controller();

        caricaRichieste();

        statoComboBox.addActionListener(
                e -> caricaRichieste()
        );

        accettaButton.addActionListener(
                e -> aggiornaRichiesta(true)
        );

        rifiutaButton.addActionListener(
                e -> aggiornaRichiesta(false)
        );

        chiudiButton.addActionListener(
                e -> chiudiFinestra()
        );
    }

    private void caricaRichieste() {

        String statoSelezionato =
                (String) statoComboBox.getSelectedItem();

        if ("TUTTE".equals(statoSelezionato)) {

            richieste =
                    controller.VisualizzaRichieste(null);

        } else {

            StatoRichiesta stato =
                    StatoRichiesta.valueOf(
                            statoSelezionato
                    );

            richieste =
                    controller.VisualizzaRichieste(
                            stato
                    );
        }

        DefaultListModel<String> model =
                new DefaultListModel<>();

        if (richieste.isEmpty()) {

            model.addElement(
                    "Nessuna richiesta trovata."
            );

        } else {

            for (RichiestaTirocinio richiesta :
                    richieste) {

                String testo =
                        "ID: "
                                + richiesta.getId()
                                + " | Studente: "
                                + richiesta.getStudente().getMatricola()
                                + " | Tirocinio: "
                                + richiesta.getTirocinio().getId()
                                + " | Stato: "
                                + richiesta.getStato();

                model.addElement(testo);
            }
        }

        richiesteList.setModel(model);
    }

    private void aggiornaRichiesta(
            boolean accetta) {

        int indice =
                richiesteList.getSelectedIndex();

        if (indice < 0
                || richieste.isEmpty()
                || indice >= richieste.size()) {

            JOptionPane.showMessageDialog(
                    mainPanel,
                    "Seleziona una richiesta.",
                    "Errore",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        RichiestaTirocinio richiesta =
                richieste.get(indice);

        controller.AccettaORifiutaRichiesta(
                richiesta,
                accetta
        );

        JOptionPane.showMessageDialog(
                mainPanel,
                accetta
                        ? "Richiesta accettata."
                        : "Richiesta rifiutata."
        );

        caricaRichieste();
    }

    private void chiudiFinestra() {

        Window window =
                SwingUtilities.getWindowAncestor(
                        mainPanel
                );

        if (window != null) {
            window.dispose();
        }
    }

